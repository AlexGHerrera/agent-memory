"""Optional OpenClaw importer: conversations from OpenClaw agent transcripts ("pi" JSONL format).

Source layout (config `[[openclaw_sources]]`, default root ~/.openclaw/agents):
  <root>/<agent>/sessions/*.jsonl          one transcript per session

Record shapes understood (one JSON object per line):
  {"type": "session", "id": "<session id>", "timestamp": "...", "cwd": "..."}
  {"type": "message", "id": "<message id>", "timestamp": "<ISO 8601>",
   "message": {"role": "user" | "assistant" | "toolResult",
               "content": "text" | [{"type": "text", "text": "..."}, {"type": "toolCall", "name": "...",
                                    "arguments": {...}}, {"type": "thinking", ...}, {"type": "image", ...}]}}

Only conversational TEXT is kept: what the human wrote (without the channel metadata envelopes OpenClaw adds) and
the assistant replies in turns a human started (text + messages sent with the `message` tool). Excluded: cron,
heartbeat, boot and subagent prompts, tool calls and results, reasoning and images. Idempotent: uid per message id
with INSERT OR IGNORE; unchanged files are skipped (ingest_state) and changed files are read again from the start.
Stored as source `openclaw`, project `openclaw-<agent>`, sessions `oc:<agent>:<session id>`.

The format is OpenClaw's internal transcript format: if a newer OpenClaw version changes it, adapt
`_pi_records` or convert the transcripts to the generic JSONL format described in docs/INGESTION.md.
"""
from __future__ import annotations

import json
import logging
import re
from collections import Counter
from pathlib import Path

from .db import SOURCE_OPENCLAW, parse_ts
from .secrets_filter import credentials_dump

log = logging.getLogger("agent_memory.openclaw")

# ---------------------------------------------------------------- user text cleanup
_STAMP = re.compile(r"^\[(?:Mon|Tue|Wed|Thu|Fri|Sat|Sun) \d{4}-\d{2}-\d{2} \d{2}:\d{2}(?::\d{2})? UTC\]\s*")
# Automatic prompts generated by the OpenClaw runtime (not written by a human).
_AUTO_START = (
    "[cron:", "Read HEARTBEAT.md", "[OpenClaw heartbeat poll]", "You are running a boot check",
    "Pre-compaction memory flush", "Write a dream diary", "[Subagent Context]", "[Inter-session message]",
    "You are a memory search agent", "OpenClaw runtime context", "OpenClaw assembled context",
    "Based on this conversation, generate", "# AGENTS.md instructions", "<turn_aborted>", "<environment_context>",
    "<user_instructions>", "[Startup context loaded by runtime]", "An async command you ran",
    "A background task completed",
)
_AUTO_ANY = ("A new session was started via /new or /reset", "Session was just compacted",
             "An async command you ran earlier has completed", "A background task completed", "reply HEARTBEAT_OK",
             "reply with ONLY: NO_REPLY", "Execute your Session Startup sequence")
_BLOCKS = [
    re.compile(r"BEGIN_QUOTED_NOTES.*?END_QUOTED_NOTES", re.S),
    re.compile(r"<active_memory_plugin>.*?</active_memory_plugin>", re.S),
    re.compile(r"<<<EXTERNAL_UNTRUSTED_CONTENT[^>]*>>>.*?<<<END_EXTERNAL_UNTRUSTED_CONTENT[^>]*>>>", re.S),
    re.compile(r"<<<BEGIN_OPENCLAW_INTERNAL_CONTEXT>>>.*?<<<END_OPENCLAW_INTERNAL_CONTEXT>>>", re.S),
    re.compile(r"\[Reply chain[^\]]*\].*?\[/Reply chain\]", re.S),
    re.compile(r"<conversation_context>.*?</conversation_context>", re.S),
    re.compile(r"⟦oc:project-context⟧.*?⟦/oc:project-context⟧", re.S),
    re.compile(r"^Conversation context \(untrusted[^\n]*\):\n(?:[^\n]+\n?)*", re.M),
]
# "X (untrusted ...):" blocks followed by ```json ... ``` (Conversation info, Sender, Replied message...)
_META = re.compile(r"^[^\n]*\(untrusted[^\n]*\):[ \t]*\n\\?```[a-z]*\n.*?\n\\?```[ \t]*$", re.S | re.M)
_SENDER = re.compile(r"^Sender \(untrusted metadata\):", re.M)
_DROP_LINE = re.compile(
    r"^(?:System(?: \(untrusted\))?: \[.*|Current time: .*|Reference UTC: .*|To send an image back.*|"
    r"Delivery: .*|Untrusted context \(metadata.*|\[Untrusted daily memory: .*|\[Queued messages while agent.*|"
    r"---|Queued #\d+ \(from [^)]*\)|\.\.\.\[(?:additional startup memory )?truncated\]\.\.\.|Source: External|"
    r"UNTRUSTED (?:Discord|Telegram) message body|Note: The previous agent run was aborted by the user\..*)\s*$", re.M)
_MEDIA = re.compile(r"^\[media attached(?: \d+/\d+)?: [^\n]*\]\s*$|^\[media attached: \d+ files\]\s*$", re.M)
_MEDIA_TAG = re.compile(r"<media:(\w+)>(?: \(\d+ files?\))?")
_THREAD = re.compile(r"^\[Thread starter - for context\]\n[^\n]*\n", re.M)
_AUDIO = re.compile(r"\[Audio\]\nUser text:\n.*?Transcript:\n", re.S)
_AUDIO2 = re.compile(r"\[Audio transcript \(machine-generated, untrusted\)\]:\s*")
_BASE64 = re.compile(r"data:[a-z]+/[\w.+-]+;base64,[A-Za-z0-9+/=]+|[A-Za-z0-9+/]{400,}={0,2}")
_REPLY_TAG = re.compile(r"\[\[\s*reply_to[^\]]*\]\]\s*")
_SILENT = re.compile(r"^(?:[A-Z][A-Z0-9_]{2,}|NO_REPLY|HEARTBEAT_OK)\.?$")
_TAG_RE = re.compile(r"\[REDACTED:[^\]]*\]")


def clean_user_text(text: str, strict: bool = False) -> str | None:
    """Text written by the human, without envelopes. None if the message is automatic (cron, heartbeat...).

    strict (agents that are not primary, whose "user" is usually another agent): without a sender envelope only a
    short message counts as written by a human.
    """
    if not text:
        return None
    t = text
    if "Current user request:" in t:
        t = t.rsplit("Current user request:", 1)[1]
    head = _STAMP.sub("", t.lstrip())
    head2 = _STAMP.sub("", _DROP_LINE.sub("", t).lstrip())
    if head.startswith(_AUTO_START) or head2.startswith(_AUTO_START) or any(m in t for m in _AUTO_ANY):
        return None
    for b in _BLOCKS:
        t = b.sub("", t)
    had_sender = bool(_SENDER.search(t))
    t = _META.sub("", t)
    t = _AUDIO.sub("", t)
    t = _AUDIO2.sub("", t)
    t = _THREAD.sub("", t)
    t = _MEDIA.sub("[attachment]", t)
    t = _DROP_LINE.sub("", t)
    t = _MEDIA_TAG.sub(lambda m: f"[{m.group(1)}]", t)
    t = _BASE64.sub("[base64 omitted]", t)
    t = _STAMP.sub("", t.strip())
    t = re.sub(r"\n{3,}", "\n\n", t).strip()
    if had_sender:
        return t or None
    if strict and len(t) > 300:
        return None
    return t or None


def clean_assistant_text(text: str) -> str | None:
    t = _REPLY_TAG.sub("", text or "")
    t = _BASE64.sub("[base64 omitted]", t).strip()
    if not t or _SILENT.match(t):
        return None
    return t


def _message_tool_text(name: str | None, args) -> str | None:
    """Message sent to the human with the `message` tool (send / upload-file with a caption)."""
    if name != "message":
        return None
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except json.JSONDecodeError:
            return None
    if not isinstance(args, dict):
        return None
    action = args.get("action")
    if action == "send":
        return clean_assistant_text(args.get("message") or args.get("text") or "")
    if action in ("upload-file", "send-file", "sendAttachment") and args.get("caption"):
        return clean_assistant_text(f"[file sent] {args['caption']}")
    return None


def mostly_secret(original: str, redacted: str) -> bool:
    """True if less than half of the text is left after redaction (the message was mostly a secret)."""
    left = len(_TAG_RE.sub("", redacted).strip())
    return redacted != original and left < 0.5 * len(original.strip())


# ---------------------------------------------------------------- ingestor
class OpenClawIngestor:
    def __init__(self, base):
        self.b = base                # agent_memory.ingest.Ingestor
        self.excl = Counter()        # reason -> number of excluded messages
        self.kept = Counter()        # role -> number of messages that pass the filter

    def _add(self, uid, machine, project, sid, role, ts, text, file_path) -> None:
        red, n = self.b.sfilter.redact(text)
        if credentials_dump(text) or mostly_secret(text, red):
            self.excl["mostly_secret"] += 1
            return
        self.kept[role] += 1
        # The already redacted text is passed; add_message filters it again (idempotent) and adds these redactions
        if self.b.add_message(uid, SOURCE_OPENCLAW, machine, project, sid, role, ts, red, prior_redactions=n):
            self.b._touch_session(sid, SOURCE_OPENCLAW, machine, project, None, file_path)

    def _unchanged(self, path: Path) -> bool:
        st = path.stat()
        row = self.b.conn.execute("SELECT size, mtime FROM ingest_state WHERE path=?", (str(path),)).fetchone()
        return bool(row and row["size"] == st.st_size and row["mtime"] == st.st_mtime)

    def _done(self, path: Path) -> None:
        st = path.stat()
        self.b.conn.execute("INSERT OR REPLACE INTO ingest_state(path, offset, size, mtime) VALUES (?,?,?,?)",
                            (str(path), st.st_size, st.st_size, st.st_mtime))
        self.b.conn.commit()

    def _pi_records(self, agent: str, records, sid_default: str, file_path: str, machine: str,
                    strict: bool) -> None:
        """records: iterable of pi-format dicts in order. Keeps the turn state (did a human start it?)."""
        project, sid, human = f"openclaw-{agent}", f"oc:{agent}:{sid_default}", False
        for r in records:
            typ = r.get("type")
            if typ == "session":
                sid = f"oc:{agent}:{r.get('id') or sid_default}"
                continue
            if typ != "message":
                continue
            m = r.get("message") or {}
            role, content, mid = m.get("role"), m.get("content"), r.get("id")
            ts = parse_ts(r.get("timestamp"))
            if not mid or ts is None:
                continue
            if role == "user":
                if isinstance(content, str):
                    raw, images = content, 0
                else:
                    blocks = [b for b in content or [] if isinstance(b, dict)]
                    raw = "\n".join(b.get("text", "") for b in blocks if b.get("type") == "text")
                    images = sum(1 for b in blocks if b.get("type") == "image")
                    self.excl["images"] += images
                text = clean_user_text(raw, strict=strict)
                if text is None and images and not raw.strip():
                    text = "[image]"
                human = text is not None
                if not human:
                    self.excl["automatic_prompts"] += 1
                    continue
                if images and text != "[image]":
                    text += "\n[image]"
                self._add(f"ocs:{agent}:{mid}", machine, project, sid, "user", ts, text, file_path)
            elif role == "assistant":
                parts = []
                blocks = content if isinstance(content, list) else [{"type": "text", "text": content}]
                for i, b in enumerate(blocks):
                    if not isinstance(b, dict):
                        continue
                    bt = b.get("type")
                    if bt == "text":
                        parts.append((i, clean_assistant_text(b.get("text", ""))))
                    elif bt == "toolCall":
                        sent = _message_tool_text(b.get("name"), b.get("arguments"))
                        if sent:
                            parts.append((i, sent))
                        else:
                            self.excl["tool_calls"] += 1
                    elif bt == "thinking":
                        self.excl["reasoning"] += 1
                    elif bt == "image":
                        self.excl["images"] += 1
                for i, text in parts:
                    if not text:
                        self.excl["empty_or_no_reply"] += 1
                    elif not human:
                        self.excl["replies_to_automatic"] += 1
                    else:
                        self._add(f"ocs:{agent}:{mid}:{i}", machine, project, sid, "assistant", ts, text, file_path)
            else:
                self.excl["tool_results"] += 1

    @staticmethod
    def _json_lines(path: Path):
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                try:
                    rec = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if isinstance(rec, dict):
                    yield rec

    def ingest_file(self, agent: str, path: Path, machine: str = "openclaw", strict: bool = False) -> None:
        if self._unchanged(path):
            return
        stem = re.search(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})", path.name)
        self._pi_records(agent, self._json_lines(path), stem.group(1) if stem else path.stem, str(path), machine,
                         strict)
        self.b.stats.files += 1
        self._done(path)

    @staticmethod
    def session_files(agent_dir: Path) -> list[Path]:
        d = agent_dir / "sessions"
        if not d.is_dir():
            return []
        return sorted(p for p in d.iterdir() if p.is_file() and p.name.endswith(".jsonl")
                      and "trajectory" not in p.name)

    def ingest_root(self, src) -> dict:
        """src: config.OpenClawSource. Returns counters (also merged into the base ingestor stats)."""
        root = Path(src.path)
        if not root.is_dir():
            log.info("OpenClaw source does not exist, skipping: %s", root)
            return {}
        agents = src.agents or sorted(p.name for p in root.iterdir() if p.is_dir())
        for agent in agents:
            for p in self.session_files(root / agent):
                try:
                    self.ingest_file(agent, p, src.machine, strict=agent not in src.primary_agents)
                except Exception:  # a corrupt file does not stop ingestion
                    log.exception("error ingesting %s", p)
        return {"kept_by_role": dict(self.kept), "excluded_by_reason": dict(self.excl)}
